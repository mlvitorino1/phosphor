import type { EventRecord, Region } from "@/lib/domain/types";

export type NewsStatus = "pending" | "approved" | "rejected" | "blocked" | "deleted";
export type UserAccount = {
  id: string;
  email: string;
  name: string;
  salt: string;
  hash: string;
  createdAt: string;
  resetHash?: string;
  resetExpiresAt?: string;
  verifyHash?: string;
  verifyExpiresAt?: string;
  emailVerified?: boolean;
  alertPrefs?: { enabled: boolean; minRisk: number; supplyChainOnly: boolean; latamOnly: boolean };
};
export type NewsCandidate = {
  id: string;
  url: string;
  title: string;
  domain: string;
  language: string;
  sourceCountry: string;
  publishedAt: string;
  capturedAt: string;
  status: NewsStatus;
  discoverySource?: string;
  discoveryMethod?: "gdelt" | "rss" | "section";
  description?: string;
  category?: EventRecord["category"];
  impact?: EventRecord["impact"];
  location?: string;
  country?: string;
  region?: Region;
  lat?: number;
  lng?: number;
  geoPrecision?: "point" | "country";
  summary?: string;
  verifiedLevel?: number | null;
  publicationMode?: "automatic" | "reviewed";
  autoPublicationDisabled?: boolean;
  reviewedAt?: string;
  approvedAt?: string;
  expiresAt?: string;
  verificationUrl?: string;
  aiAnalysis?: {
    at: string;
    model: string;
    summary: string;
    category: EventRecord["category"];
    impact: EventRecord["impact"];
    location: string;
    entities: { name: string; type: string; quote: string }[];
    relations: { from: string; to: string; type: string; quote: string }[];
    causalClaims: { claim: string; quote: string }[];
    evidence: string[];
  };
};
export type LocalState = {
  admin?: { salt: string; hash: string; secret: string };
  users?: Record<string, UserAccount>;
  userSecret?: string;
  alertDeliveries?: Record<string, string>;
  sources: Record<string, boolean>;
  eventOverrides: Record<string, Partial<EventRecord> & { hidden?: boolean }>;
  news: Record<string, NewsCandidate>;
  newsLastAttempt?: string;
  newsLastError?: string;
};
